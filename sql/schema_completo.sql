
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS BOOLEAN
LANGUAGE sql
SECURITY DEFINER
STABLE
SET search_path = public
AS $$
    SELECT EXISTS (
        SELECT 1 FROM public.profiles
        WHERE id = auth.uid() AND role = 'admin'
    );
$$;

CREATE TABLE IF NOT EXISTS public.profiles (
    id         UUID        PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    name       TEXT        NOT NULL,
    dni        TEXT        NOT NULL,
    role       TEXT        NOT NULL DEFAULT 'client'
                           CHECK (role IN ('client', 'admin')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Índice útil para búsquedas por DNI en el panel de admin
CREATE INDEX IF NOT EXISTS idx_profiles_dni ON public.profiles(dni);

-- RLS: activar seguridad por fila
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

-- Todos los usuarios autenticados pueden leer perfiles
CREATE POLICY "profiles_select_authenticated"
    ON public.profiles FOR SELECT
    USING (auth.role() = 'authenticated');

-- Cada usuario puede editar sólo su propio perfil
CREATE POLICY "profiles_update_own"
    ON public.profiles FOR UPDATE
    USING (auth.uid() = id);

-- Los administradores pueden hacer cualquier operación sobre cualquier perfil

CREATE POLICY "profiles_all_admin"
    ON public.profiles FOR ALL
    USING (public.is_admin());


