    USING (public.is_admin());


-- ──────────────────────────────────────────────────────────────────────────────
-- 5. TABLA: RESERVATIONS
--    Una reserva = un cliente ocupa un spot (1-32) en una clase específica.
--    La clave UNIQUE (class_id, spot_number) garantiza que no haya colisiones.
-- ──────────────────────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS public.reservations (
    id           UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    profile_id   UUID        NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    class_id     BIGINT      NOT NULL REFERENCES public.classes(id) ON DELETE CASCADE,
    spot_number  INTEGER     NOT NULL CHECK (spot_number BETWEEN 1 AND 32),
    phone_yape   TEXT        NOT NULL,
    code_yape    TEXT        NOT NULL,
    status       TEXT        NOT NULL DEFAULT 'confirmed'
                             CHECK (status IN ('pending', 'confirmed', 'cancelled')),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- Garantiza que el mismo spot no sea reservado dos veces en la misma clase
    UNIQUE (class_id, spot_number)
);

CREATE INDEX IF NOT EXISTS idx_reservations_profile_id ON public.reservations(profile_id);
CREATE INDEX IF NOT EXISTS idx_reservations_class_id   ON public.reservations(class_id);
CREATE INDEX IF NOT EXISTS idx_reservations_status     ON public.reservations(status);

ALTER TABLE public.reservations ENABLE ROW LEVEL SECURITY;

-- Usuarios autenticados pueden ver qué spots están ocupados en cualquier clase
-- (necesario para renderSpotSelection → getOccupiedSpots)
CREATE POLICY "reservations_select_authenticated"
    ON public.reservations FOR SELECT
    USING (auth.role() = 'authenticated');

-- Un cliente sólo puede crear reservas donde el profile_id sea el suyo
CREATE POLICY "reservations_insert_own"
    ON public.reservations FOR INSERT
    WITH CHECK (auth.uid() = profile_id);

-- Un cliente puede cancelar (borrar) sólo sus propias reservas
CREATE POLICY "reservations_delete_own"
    ON public.reservations FOR DELETE
    USING (auth.uid() = profile_id);

-- Un administrador puede hacer cualquier operación sobre cualquier reserva
CREATE POLICY "reservations_all_admin"
    ON public.reservations FOR ALL
    USING (public.is_admin());


-- ──────────────────────────────────────────────────────────────────────────────
-- 6. TRIGGER: SINCRONIZACIÓN AUTOMÁTICA DE PERFILES
--    Cuando Supabase Auth crea un usuario nuevo, este trigger lee los
--    metadatos del registro (name, dni, role) y crea automáticamente el
--    perfil en public.profiles.
--
--    El frontend envía estos metadatos en auth.signUp({ options: { data: { ... } } })
--    tal como está en js/auth.js → registerUser()
-- ──────────────────────────────────────────────────────────────────────────────

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    user_role TEXT;
BEGIN
    -- Sólo acepta 'client' o 'admin'; cualquier otro valor cae a 'client'
    user_role := CASE
        WHEN new.raw_user_meta_data->>'role' IN ('client', 'admin')
        THEN new.raw_user_meta_data->>'role'
        ELSE 'client'
    END;

    INSERT INTO public.profiles (id, name, dni, role)
    VALUES (
        new.id,
        COALESCE(NULLIF(TRIM(new.raw_user_meta_data->>'name'), ''), 'Usuario Registrado'),
        COALESCE(NULLIF(TRIM(new.raw_user_meta_data->>'dni'),  ''), '00000000'),
        user_role
    )
    ON CONFLICT (id) DO NOTHING;   -- evita error si el perfil ya fue creado manualmente

    RETURN NEW;
END;
$$;

-- Enlazar el trigger a auth.users
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW
    EXECUTE FUNCTION public.handle_new_user();


