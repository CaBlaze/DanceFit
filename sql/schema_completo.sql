-- ──────────────────────────────────────────────────────────────────────────────
-- 4. TABLA: CLASSES
--    Catálogo de clases de baile del estudio.
-- ──────────────────────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS public.classes (
    id            BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT          NOT NULL,
    level         TEXT          NOT NULL,                    -- "BEGINNER", "ADVANCED", "OPEN LEVEL", "SPECIAL WORKSHOP"
    level_color   TEXT          NOT NULL,                    -- Hex color para la badge del nivel
    time          TEXT          NOT NULL,                    
    instructor_id BIGINT        REFERENCES public.instructors(id) ON DELETE SET NULL,
    branch_id     BIGINT        REFERENCES public.branches(id) ON DELETE SET NULL,
    theme         TEXT          NOT NULL,                    -- Temática, ej: "Neón Night"
    style         TEXT          NOT NULL,                    -- Estilo, ej: "Salsa", "Reggaetón"
    price         NUMERIC(10,2) NOT NULL,
    duration      TEXT          NOT NULL,                    -- ej: "90 min"
    emoji         TEXT          NOT NULL,                    -- Emoji representativo de la clase
    class_date    DATE          NOT NULL DEFAULT CURRENT_DATE,
    created_at    TIMESTAMPTZ   NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_classes_class_date    ON public.classes(class_date);
CREATE INDEX IF NOT EXISTS idx_classes_instructor_id ON public.classes(instructor_id);
CREATE INDEX IF NOT EXISTS idx_classes_style         ON public.classes(style);

ALTER TABLE public.classes ENABLE ROW LEVEL SECURITY;

-- Lectura pública de clases
CREATE POLICY "classes_select_public"
    ON public.classes FOR SELECT
    USING (true);

-- Sólo administradores gestionan clases
CREATE POLICY "classes_all_admin"
